export function translateText(source, locale = currentLocale()) {
  if (locale !== 'en') return source;
  const raw = String(source), text = raw.trim();
  let translated = englishUI[text];
  if (translated === undefined && text.endsWith(' ↗') && englishUI[text.slice(0,-2)]) translated = englishUI[text.slice(0,-2)] + ' ↗';
  if (translated === undefined) {
    if (/^正在驶向/.test(text)) translated = 'Travelling to ' + text.slice(4);
    else if (/^正在停靠：/.test(text)) translated = 'Docking: ' + text.slice(5);
    else if (/^发现 \d+ 艘$/.test(text)) translated = text.replace(/^发现 (\d+) 艘$/, 'Discover $1');
    else if (/^\d+ 艘作品星舰已显现/.test(text)) translated = text.replace(/^(\d+) 艘作品星舰已显现。选择一艘，驾驶飞船靠近。$/, '$1 projects revealed. Choose one to explore.');
    else if (text.endsWith('封面')) translated = text.slice(0, -2) + ' — cover';
    else if (text.endsWith('的作者原稿')) translated = text.slice(0, -5) + ' — original manuscript';
    else for (const prefix of ['当前航向 /', '在作品中看看 /', '原创 /']) {
      if (text.startsWith(prefix)) { translated = englishUI[prefix] + text.slice(prefix.length); break; }
    }
    if (translated === undefined && text.includes('已探索 · 选择坐标')) translated = text.replace('已探索 · 选择坐标', englishUI['已探索 · 选择坐标']);
    if (translated === undefined && text.includes(' / 信号已解码')) translated = text.replace(' / 信号已解码', ' / Project discovered');
    if (translated === undefined && /^SIGNAL \d+ \/ (待探索|已探索)$/.test(text)) translated = text.replace('待探索','Undiscovered').replace('已探索','Discovered');
  }
  return translated === undefined ? raw : raw.replace(text, translated);
}
export const t = translateText;
export function translateMarkup(html, locale = currentLocale()) {
  if (locale !== 'en') return html;
  return html.replace(/>([^<>]+)</g, (_, text) => '>' + t(text, locale) + '<')
    .replace(/(aria-label|title|alt)="([^"]*)"/g, (_, key, text) => key + '="' + t(text, locale) + '"');
}
export function localizeDOM(root = document.body) {
  if (currentLocale() !== 'en') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest('script,style,[data-original-text],[lang="zh-CN"]')) continue;
    const translated = t(node.nodeValue);
    if (translated !== node.nodeValue) node.nodeValue = translated;
  }
  for (const el of root.querySelectorAll('[aria-label],[title],[alt]')) for (const key of ['aria-label', 'title', 'alt']) {
    const value = el.getAttribute(key); if (value !== null && t(value) !== value) el.setAttribute(key, t(value));
  }
}
